# Shared by local deployment runners. Caller owns the SQL transaction and rollback file list.
function Backup-CrmLogoDatabase([Data.SqlClient.SqlConnection]$Connection) {
 $builder=[Data.SqlClient.SqlConnectionStringBuilder]::new($Connection.ConnectionString)
 if($builder.DataSource -notin @('localhost','.','(local)')){throw 'File logo migration requires the local deployment runner.'}
 $cmd=$Connection.CreateCommand()
 try {
  $cmd.CommandText="SELECT CONVERT(nvarchar(4000),SERVERPROPERTY('InstanceDefaultBackupPath'))";$folder=[string]$cmd.ExecuteScalar()
  if(-not $folder){throw 'A verified full backup is required.'}
  $backup=Join-Path $folder ('CustomerFileLogos-'+[guid]::NewGuid().ToString('N')+'.bak')
  $cmd.CommandTimeout=300;$cmd.CommandText='BACKUP DATABASE ['+$builder.InitialCatalog.Replace(']',']]')+'] TO DISK=@Path WITH COPY_ONLY,CHECKSUM;';[void]$cmd.Parameters.AddWithValue('@Path',$backup);[void]$cmd.ExecuteNonQuery()
  $cmd.CommandText='RESTORE VERIFYONLY FROM DISK=@Path WITH CHECKSUM;';[void]$cmd.ExecuteNonQuery()
  Write-Output "Verified full backup: $backup"
 } finally {$cmd.Dispose()}
}

function Export-CrmLogoFiles([Data.SqlClient.SqlConnection]$Connection,[Data.SqlClient.SqlTransaction]$Transaction,[string]$StorageRoot,[Collections.Generic.List[string]]$CreatedFiles) {
 $root=[IO.Path]::GetFullPath($StorageRoot)
 [void][IO.Directory]::CreateDirectory($root)
 $cmd=$Connection.CreateCommand();$cmd.Transaction=$Transaction;$cmd.CommandTimeout=120
 try {
  $cmd.CommandText="DECLARE @Lock int;EXEC @Lock=sys.sp_getapplock @Resource=N'CRM_Write',@LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=15000;IF @Lock<0 THROW 51990,'CRM logo migration is busy.',1;IF COL_LENGTH('dbo.CRM_Accounts','Logo_Url') IS NULL ALTER TABLE dbo.CRM_Accounts ADD Logo_Url nvarchar(260) NULL;"
  [void]$cmd.ExecuteNonQuery()
  $cmd.CommandText="SELECT COL_LENGTH('dbo.CRM_Accounts','Logo_Data')";$hasBytes=$cmd.ExecuteScalar()
  if($hasBytes -is [DBNull]){return}
  $cmd.CommandText='SELECT ID,Logo_Data,Logo_Url FROM dbo.CRM_Accounts WITH(UPDLOCK,HOLDLOCK) WHERE Logo_Data IS NOT NULL'
  $rows=[Data.DataTable]::new();[void]([Data.SqlClient.SqlDataAdapter]::new($cmd)).Fill($rows)
  foreach($row in $rows.Rows) {
   $url=[string]$row.Logo_Url
   if(-not $url){$url='/FileManager/CustomerLogos/'+[guid]::NewGuid().ToString('N')+'.png'}
   if($url -cnotmatch '^/FileManager/CustomerLogos/[a-f0-9]{32}\.png$'){throw 'Unexpected legacy logo URL.'}
   $path=[IO.Path]::GetFullPath((Join-Path $root ([IO.Path]::GetFileName($url))))
   if(-not $path.StartsWith($root.TrimEnd('\')+'\',[StringComparison]::OrdinalIgnoreCase)){throw 'Logo export escaped its destination.'}
   if(-not [IO.File]::Exists($path)) {
    $stream=[IO.File]::Open($path,[IO.FileMode]::CreateNew,[IO.FileAccess]::Write,[IO.FileShare]::None)
    $CreatedFiles.Add($path)
    try{$stream.Write([byte[]]$row.Logo_Data,0,$row.Logo_Data.Length)}finally{$stream.Dispose()}
   }
   $sha=[Security.Cryptography.SHA256]::Create()
   try {
    $expected=[Convert]::ToBase64String($sha.ComputeHash([byte[]]$row.Logo_Data))
    $actual=[Convert]::ToBase64String($sha.ComputeHash([IO.File]::ReadAllBytes($path)))
    if($actual -ne $expected){throw 'Logo file verification failed; database bytes are retained.'}
   } finally {$sha.Dispose()}
   $cmd.Parameters.Clear();$cmd.CommandText='UPDATE dbo.CRM_Accounts SET Logo_Url=@Url WHERE ID=@ID'
   [void]$cmd.Parameters.AddWithValue('@Url',$url);[void]$cmd.Parameters.AddWithValue('@ID',[int]$row.ID);[void]$cmd.ExecuteNonQuery()
  }
  Write-Host ('Exported and SHA-256 verified '+$rows.Rows.Count+' existing customer logos.')
 } finally {$cmd.Dispose()}
}

function Apply-CrmFileLogoSql([Data.SqlClient.SqlConnection]$Connection,[Data.SqlClient.SqlTransaction]$Transaction,[string]$CrmDirectory) {
 $files=@((Join-Path $CrmDirectory '012_CRM_FileLogos.sql'))
 $check=$Connection.CreateCommand();$check.Transaction=$Transaction;$check.CommandText="SELECT OBJECT_ID('dbo.Customer_Dashboard','P')"
 try{if($check.ExecuteScalar() -isnot [DBNull]){$files+=Join-Path $CrmDirectory '../CustomerPortal/009_FileLogos.sql'}}finally{$check.Dispose()}
 foreach($file in $files){foreach($batch in [regex]::Split([IO.File]::ReadAllText($file),'(?im)^\s*GO\s*$')){
  if(-not $batch.Trim()){continue};$cmd=$Connection.CreateCommand();$cmd.Transaction=$Transaction;$cmd.CommandTimeout=120;$cmd.CommandText=$batch
  try{[void]$cmd.ExecuteNonQuery()}finally{$cmd.Dispose()}
 }}
}

function Remove-CrmStagedLogos([Collections.Generic.List[string]]$CreatedFiles) {
 # Only exact files generated by this transaction are removed; never recurse or enumerate storage.
 foreach($file in $CreatedFiles){try{[IO.File]::Delete($file)}catch{Write-Warning 'A staged logo could not be removed after rollback.'}}
}
