#!/usr/bin/env python3
"""Generate a LIMITED development baseline from the published LINQ-to-SQL contracts.

These are new CRUD implementations, not recovered production business rules.
Only the ten core entities below are implemented; no placeholder procedures are made.
"""
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
NS = {"d": "http://schemas.microsoft.com/linqtosql/dbml/2007"}
TABLES = ("Users_Types", "Brands", "Branches", "Departments", "JobTitles",
          "Shift", "Genders", "Nationalities", "UsersMembers", "News")


def generate():
    document = ET.parse(ROOT / "src/ProstoERP.Infrastructure/Generated/LinqToSql/Prosto_ERP_DataClasses.dbml")
    functions = document.findall("d:Function", NS)
    definitions = {}
    for table in TABLES:
        functions_for_table = [f for f in functions if re.match(
            r"(?:Select|Insert|Update)_" + re.escape(table) + r"(?:_|$)", f.get("Method"))]
        columns = {}
        for f in functions_for_table:
            if f.get("Method") not in ("Select_" + table + "_ByID", "Insert_" + table):
                continue
            for c in f.findall("d:ElementType/d:Column", NS):
                name = c.get("Name")
                # Joined display titles belong to related tables, not this table.
                if name not in ("Title_Ar", "Title_En") and re.search(r"Title_(?:Ar|En)$", name, re.I):
                    continue
                if name in ("NewID", "NewPID"):
                    continue
                columns[name] = re.sub(r"\s+NOT NULL$", "", c.get("DbType"), flags=re.I)
            if f.get("Method").startswith("Insert_"):
                for p in f.findall("d:Parameter", NS):
                    if p.get("Direction") != "InOut":
                        columns[p.get("Name")] = p.get("DbType")
        definitions[table] = columns

    sql = ["-- Generated by scripts/generate_development_schema.py. DEVELOPMENT ONLY.",
           "-- New CRUD behavior inferred from DBML; not the original ERP database.",
           "IF DB_NAME() <> 'Prosto_ERP_Development' THROW 51000, 'Wrong database for development schema.', 1;",
           "GO"]
    for table, columns in definitions.items():
        pk = "PID" if table == "News" else "ID"
        declarations = []
        for name, dbtype in columns.items():
            if name == pk:
                declaration = f"[{name}] int IDENTITY(1,1) NOT NULL PRIMARY KEY"
            elif name == "IsDeleted":
                declaration = f"[{name}] bit NOT NULL DEFAULT(0)"
            elif name == "IsActive":
                declaration = f"[{name}] bit NOT NULL DEFAULT(1)"
            elif name == "AddedDate":
                declaration = f"[{name}] datetime NOT NULL DEFAULT(GETUTCDATE())"
            elif name == "Password":
                declaration = f"[{name}] {dbtype} COLLATE Latin1_General_100_BIN2 NULL"
            else:
                declaration = f"[{name}] {dbtype} NULL"
            declarations.append("  " + declaration)
        sql += [f"IF OBJECT_ID('dbo.{table}', 'U') IS NULL", f"CREATE TABLE dbo.[{table}](",
                ",\n".join(declarations), ");", "GO"]

    supported = []
    for f in functions:
        name = f.get("Method")
        match = re.match(r"(Select|Insert|Update)_(" + "|".join(TABLES) + r")(?:_(.*))?$", name)
        if not match:
            continue
        operation, table, suffix = match.groups()
        columns = definitions[table]
        params = f.findall("d:Parameter", NS)
        results = f.findall("d:ElementType/d:Column", NS)
        mapping = {p.get("Name"): p.get("Name") for p in params}
        for key in mapping:
            if key not in columns and key.replace("_", "") in columns:
                mapping[key] = key.replace("_", "")
        if any(mapping[p.get("Name")] not in columns for p in params if p.get("Direction") != "InOut"):
            continue
        declaration = ", ".join("@" + p.get("Name") + " " + p.get("DbType") +
                                (" OUTPUT" if p.get("Direction") == "InOut" else " = NULL") for p in params)
        body = []
        if operation == "Select":
            if suffix not in ("All", "ForDDL", "Filter") and not (suffix or "").startswith("By"):
                continue
            joins, expressions = [], []
            for c in results:
                column = c.get("Name")
                if column in columns:
                    expressions.append(f"t.[{column}]")
                elif table == "UsersMembers" and column.startswith(("GenderTitle_", "NationalityTitle_")):
                    gender = column.startswith("Gender")
                    other, fk = ("Genders", "Gender") if gender else ("Nationalities", "Nationality")
                    alias = "g" if gender else "n"
                    join = f"LEFT JOIN dbo.[{other}] {alias} ON {alias}.ID=t.[{fk}]"
                    if join not in joins:
                        joins.append(join)
                    expressions.append(f"{alias}.[Title_{column.rsplit('_', 1)[1]}] AS [{column}]")
                elif table in ("Departments", "JobTitles") and re.match(r"(?:Department|Branch|Brand)Title_(?:Ar|En)$",
                                                                        column):
                    if table == "JobTitles":
                        needed = ["JOIN dbo.Departments d ON d.ID=t.DepartmentID",
                                  "JOIN dbo.Branches b ON b.ID=d.BranchID",
                                  "JOIN dbo.Brands br ON br.ID=b.BrandID"]
                    else:
                        needed = ["JOIN dbo.Branches b ON b.ID=t.BranchID",
                                  "JOIN dbo.Brands br ON br.ID=b.BrandID"]
                    for join in needed:
                        if join not in joins:
                            joins.append(join)
                    alias = "d" if column.startswith("Department") else "b" if column.startswith("Branch") else "br"
                    expressions.append(f"{alias}.[Title_{column.rsplit('_', 1)[1]}] AS [{column}]")
                elif table == "JobTitles" and column in ("DepartmentID1", "BranchID", "BrandID"):
                    needed = ["JOIN dbo.Departments d ON d.ID=t.DepartmentID",
                              "JOIN dbo.Branches b ON b.ID=d.BranchID", "JOIN dbo.Brands br ON br.ID=b.BrandID"]
                    for join in needed:
                        if join not in joins:
                            joins.append(join)
                    alias = {"DepartmentID1": "d", "BranchID": "b", "BrandID": "br"}[column]
                    expressions.append(f"{alias}.ID AS [{column}]")
                else:
                    break
            else:
                where = ["ISNULL(t.IsDeleted,0)=0"] if "IsDeleted" in columns else []
                for p in params:
                    key = p.get("Name")
                    equality = f"t.[{mapping[key]}]=@{key}"
                    where.append(f"(@{key} IS NULL OR {equality})" if suffix == "Filter" else equality)
                if suffix == "ByUserName_Password":
                    where.append("ISNULL(t.IsActive,1)=1")
                    # Ciphertext comparisons must be case-sensitive, even on a CI database.
                    where = [
                        x.replace("t.[Password]=@Password", "t.[Password] COLLATE Latin1_General_100_BIN2=@Password")
                        for x in where]
                body = ["SELECT " + ", ".join(expressions) + f" FROM dbo.[{table}] t " + " ".join(joins)
                        + (" WHERE " + " AND ".join(where) if where else "") + ";"]
        elif operation == "Insert":
            incoming = [p for p in params if p.get("Direction") != "InOut"]
            names = [p.get("Name") for p in incoming]
            values = ["COALESCE(@AddedDate,GETUTCDATE())" if key == "AddedDate" else
                      "COALESCE(@IsActive,1)" if key == "IsActive" else
                      "COALESCE(@IsDeleted,0)" if key == "IsDeleted" else "@" + key for key in names]
            body = [f"INSERT dbo.[{table}](" + ",".join("[" + mapping[k] + "]" for k in names)
                    + ") VALUES(" + ",".join(values) + ");"]
            for p in params:
                if p.get("Direction") == "InOut":
                    body.append("SET @" + p.get("Name") + "=CONVERT(int,SCOPE_IDENTITY());")
            if len(results) == 1 and results[0].get("Name") in ("NewID", "NewPID"):
                body.append("SELECT CONVERT(decimal(38,0),SCOPE_IDENTITY()) AS [" + results[0].get("Name") + "];")
        elif "ID" in mapping:
            assignments = [f"[{mapping[p.get('Name')]}]=@{p.get('Name')}" for p in params if p.get("Name") != "ID"]
            if "ModifyDate" in columns and "ModifyDate" not in mapping:
                assignments.append("[ModifyDate]=GETUTCDATE()")
            body = [f"UPDATE dbo.[{table}] SET " + ",".join(assignments) + " WHERE ID=@ID;"]
        if body:
            sql += [f"CREATE OR ALTER PROCEDURE dbo.[{name}] {declaration}", "AS", "BEGIN", "SET NOCOUNT ON;",
                    *body, "END", "GO"]
            supported.append(name)
    target = ROOT / "database/development"
    target.mkdir(exist_ok=True)
    (target / "001_Core.sql").write_text("\n".join(sql) + "\n")
    (target / "supported-procedures.txt").write_text("\n".join(supported) + "\n")
    print(f"Generated {len(definitions)} development tables and {len(supported)} real CRUD procedures.")


if __name__ == "__main__":
    generate()
