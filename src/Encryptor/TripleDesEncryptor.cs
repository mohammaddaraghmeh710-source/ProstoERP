using System;
using System.Configuration;
using System.Security.Cryptography;
using System.Text;

namespace Echo.Encrptor
{
    // Development replacement for the unavailable proprietary DLL. The public
    // name is retained for callers; the format uses AES/HMAC, not legacy 3DES.
    // Determinism is necessary because the existing SQL login compares ciphertext.
    // This format is NOT compatible with existing production password values.
    public sealed class TripleDesEncryptor
    {
        private const string Prefix = "prosto-dev1:";
        private readonly byte[] encryptionKey;
        private readonly byte[] authenticationKey;
        private readonly byte[] ivKey;

        public TripleDesEncryptor()
        {
            if (!string.Equals(ConfigurationManager.AppSettings["LocalDevelopment.Enabled"], "true", StringComparison.OrdinalIgnoreCase))
                throw new ConfigurationErrorsException("The replacement Encryptor is restricted to LocalDevelopment.Enabled=true.");
            byte[] master;
            try { master = Convert.FromBase64String(ConfigurationManager.AppSettings["LocalDevelopment.EncryptionKey"] ?? ""); }
            catch (FormatException) { throw new ConfigurationErrorsException("LocalDevelopment.EncryptionKey must be a base64 key generated by setup_development.py."); }
            if (master.Length != 32)
                throw new ConfigurationErrorsException("LocalDevelopment.EncryptionKey must contain 32 random bytes.");
            encryptionKey = Derive(master, "encryption");
            authenticationKey = Derive(master, "authentication");
            ivKey = Derive(master, "iv");
            Array.Clear(master, 0, master.Length);
        }

        private static byte[] Derive(byte[] master, string purpose)
        {
            using (var hmac = new HMACSHA256(master))
                return hmac.ComputeHash(Encoding.UTF8.GetBytes("Prosto.LocalDevelopment.v1/" + purpose));
        }

        public string Encrypt(string value)
        {
            if (value == null) throw new ArgumentNullException("value");
            var plain = Encoding.UTF8.GetBytes(value);
            var iv = new byte[16];
            using (var hmac = new HMACSHA256(ivKey))
                Buffer.BlockCopy(hmac.ComputeHash(plain), 0, iv, 0, iv.Length);
            byte[] cipher;
            using (var aes = Aes.Create())
            {
                aes.Key = encryptionKey;
                aes.IV = iv;
                using (var transform = aes.CreateEncryptor())
                    cipher = transform.TransformFinalBlock(plain, 0, plain.Length);
            }
            var payload = new byte[iv.Length + cipher.Length];
            Buffer.BlockCopy(iv, 0, payload, 0, iv.Length);
            Buffer.BlockCopy(cipher, 0, payload, iv.Length, cipher.Length);
            byte[] tag;
            using (var hmac = new HMACSHA256(authenticationKey)) tag = hmac.ComputeHash(payload);
            var result = new byte[payload.Length + tag.Length];
            Buffer.BlockCopy(payload, 0, result, 0, payload.Length);
            Buffer.BlockCopy(tag, 0, result, payload.Length, tag.Length);
            return Prefix + Convert.ToBase64String(result);
        }

        public string Decrypt(string value)
        {
            if (value == null) throw new ArgumentNullException("value");
            if (!value.StartsWith(Prefix, StringComparison.Ordinal))
                throw new CryptographicException("This replacement cannot decrypt legacy password values.");
            byte[] all;
            try { all = Convert.FromBase64String(value.Substring(Prefix.Length)); }
            catch (FormatException) { throw new CryptographicException("Invalid development ciphertext."); }
            if (all.Length < 64 || (all.Length - 48) % 16 != 0)
                throw new CryptographicException("Invalid development ciphertext.");
            var length = all.Length - 32;
            byte[] expected;
            using (var hmac = new HMACSHA256(authenticationKey)) expected = hmac.ComputeHash(all, 0, length);
            var difference = 0;
            for (var i = 0; i < expected.Length; i++) difference |= expected[i] ^ all[length + i];
            if (difference != 0) throw new CryptographicException("Development ciphertext authentication failed.");
            var iv = new byte[16];
            Buffer.BlockCopy(all, 0, iv, 0, iv.Length);
            using (var aes = Aes.Create())
            {
                aes.Key = encryptionKey;
                aes.IV = iv;
                using (var transform = aes.CreateDecryptor())
                    return Encoding.UTF8.GetString(transform.TransformFinalBlock(all, 16, length - 16));
            }
        }
    }
}
